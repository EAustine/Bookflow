/**
 * Generate tokens.css from the TypeScript source (§11).
 *
 * Consumed by the web shell, the reader engine and the marketing site.
 * Reads `dist/` rather than `src/`, so `npm run build` has to run first —
 * that keeps this script plain Node with no TS runner.
 *
 * What is emitted, and what is not:
 *
 *   - Colours, spacing, radii, border widths, font families and sizes
 *     become custom properties. These are the values a stylesheet needs.
 *   - Breakpoints become both custom properties and real `@media` rules,
 *     because a custom property cannot be used in a media query.
 *   - Elevation becomes `box-shadow`, translated from the React Native
 *     shadow model. That translation is lossy and is flagged inline
 *     rather than hidden: RN's elevation/shadowRadius do not map exactly
 *     onto CSS blur, so these are visually close, not identical.
 *   - Text *styles* are NOT emitted. They carry RN-specific line-height
 *     semantics and would be wrong as CSS; the web shell composes them
 *     from the family and size variables instead.
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const pkg = join(here, '..');

const t = await import(join(pkg, 'dist/index.js'));

const lines = [];
const seen = new Set();

function emit(name, value) {
  if (seen.has(name)) {
    throw new Error(`duplicate custom property --${name}`);
  }
  seen.add(name);
  lines.push(`  --${name}: ${value};`);
}

const kebab = (s) =>
  String(s).replace(/([a-z0-9])([A-Z])/g, '$1-$2').replace(/_/g, '-').toLowerCase();

/** Walk a nested token object into flat `prefix-a-b` names. */
function walk(prefix, obj, format) {
  for (const [k, v] of Object.entries(obj)) {
    const name = `${prefix}-${kebab(k)}`;
    if (v && typeof v === 'object' && !Array.isArray(v)) walk(name, v, format);
    else if (v !== undefined && v !== null) emit(name, format(v));
  }
}

const px = (v) => (typeof v === 'number' ? `${v}px` : String(v));
const raw = (v) => String(v);

lines.push(':root {');

walk('color', t.colors, raw);
walk('color-text', t.textColors, raw);
walk('color-bg', t.bgColors, raw);
walk('color-border', t.borderColors, raw);
walk('overlay', t.overlay, raw);

walk('space', t.space, px);
walk('spacing', t.spacing, px);
walk('radius', t.radii, px);
walk('border-width', t.borderWidth, px);
walk('font', t.fonts, (v) => `"${v}"`);
walk('font-size', t.fontSizes, px);
walk('icon-size', t.iconSize, px);
walk('breakpoint', t.breakpoints, px);
walk('layout', t.layout, px);
emit('reading-measure', px(t.readingMeasure));

// Elevation: RN shadow model -> CSS box-shadow. Lossy; see the header.
for (const [level, s] of Object.entries(t.elevation)) {
  if (!s || typeof s !== 'object') continue;
  const o = s.shadowOffset ?? { width: 0, height: 0 };
  const blur = s.shadowRadius ?? 0;
  const alpha = s.shadowOpacity ?? 0;
  const colour = s.shadowColor ?? '#000';
  emit(
    `elevation-${kebab(level)}`,
    `${px(o.width)} ${px(o.height)} ${px(blur * 2)} rgba(0,0,0,${alpha})`,
  );
  if (colour !== '#000' && colour !== '#000000') {
    lines.push(`  /* elevation ${level}: shadowColor ${colour} not representable in the rgba above */`);
  }
}

lines.push('}');
lines.push('');
lines.push('/* Breakpoints again as media queries — a custom property cannot');
lines.push('   be used in a media condition. */');
for (const [name, w] of Object.entries(t.breakpoints)) {
  if (w === 0) continue;
  lines.push(`@custom-media --${kebab(name)} (min-width: ${w}px);`);
}

const css = `/* GENERATED by packages/tokens — do not edit.
   Source: packages/tokens/src/*.ts
   Regenerate: npm run build:tokens
   ${seen.size} custom properties. */\n\n${lines.join('\n')}\n`;

mkdirSync(join(pkg, 'dist'), { recursive: true });
writeFileSync(join(pkg, 'dist/tokens.css'), css, 'utf8');

console.log(`tokens.css: ${seen.size} custom properties -> packages/tokens/dist/tokens.css`);
