/**
 * discover-doab — Edge Function that harvests DOAB over OAI-PMH and
 * normalises records into the same `DiscoverBook` shape every other
 * discovery source produces. ~128k peer-reviewed open-access academic
 * and scholarly titles — fills the contemporary-scholarship gap left
 * by the public-domain catalogs (Gutenberg, Wikisource, etc.) which
 * top out around 1928 for US works.
 *
 * Why OAI-PMH, having previously chosen REST:
 *   This function used DOAB's DSpace REST API at /rest/search until
 *   2026-10-28, when it began returning **403 to every request** —
 *   with or without the documented `Accept: application/xml`, and on
 *   the wildcard query it had always used. `/rest` is DSpace's legacy
 *   v4–6 API, deprecated upstream and slated for removal in DSpace 8,
 *   so this was never going to be a long-lived dependency. DOAB's
 *   OAI-PMH endpoint answers 200 to the same user-agent and is the
 *   interface they document for aggregators.
 *
 *   The old header argued OAI-PMH would mean digging download URLs
 *   out of "dc:identifier soup" across a wild variety of publisher
 *   hosts. That is true of the `oai_dc` prefix, and it is why REST
 *   was picked. It is NOT true of **xoai**, DOAB's full-fidelity
 *   format, which carries the bundle/bitstream tree inline —
 *   including `oapenidentifierdownloadUrl`, the same field the REST
 *   adapter keyed on, plus the THUMBNAIL bitstream's absolute URL.
 *   Measured against a live page of 100 records: 48 carried a usable
 *   `.pdf` download URL, all 48 also had a thumbnail, and 42 of the
 *   48 were library.oapen.org. So the normalisation below is the same
 *   logic reading a different envelope.
 *
 * Why PDF instead of EPUB:
 *   DOAB / OAPEN distribute academic books as PDFs almost
 *   exclusively (very few publishers provide EPUB for OA scholarly
 *   work). The PdfReader path in the app already handles import,
 *   text extraction, and reading. We surface the PDF URL through
 *   the `epubUrl` field — semantically misleading but pragmatic; the
 *   import flow downloads whatever is at `source_url` and
 *   process-book detects mime type. Adding a real `pdfUrl` field
 *   would ripple through DiscoverBook, ImportableBook, and every
 *   importer call site for no operational benefit.
 *
 * Skipping rule — records WITHOUT a `.pdf` download URL are dropped.
 *   Some DOAB records only link to a publisher landing page rather
 *   than a file. Filtering them server-side keeps the rail UX clean —
 *   every card the user sees is one they can actually add. (Note the
 *   rule is "ends in .pdf", on any host; the previous header claimed
 *   non-OAPEN hosts were dropped, but the code it described accepted
 *   them too. Behaviour is unchanged, the description is now accurate.)
 *
 * No free-text search. OAI-PMH has no search verb — only ListRecords
 *   and GetRecord, filtered by set and datestamp. A `q` parameter
 *   therefore cannot be honoured, and filtering one harvested page of
 *   100 out of 128k records would be a search in name only. Requests
 *   carrying `q` get an explicit `search_unsupported` error rather
 *   than a plausible-looking wrong answer. No caller passes one today:
 *   `fetchDoabRest` is called once, for the rail, without a query.
 *
 * XML by regex, deliberately: the same call this repo already makes in
 *   discover-opds. xoai is machine-generated by DSpace with a fixed
 *   shape; the nesting-aware readers below are enough for it and keep
 *   a parser dependency out of an edge function.
 *
 * Auth: passthrough — DOAB content is open access, no PII, anon key OK.
 */

const CORS_HEADERS = {
  'Access-Control-Allow-Origin': '*',
  'Access-Control-Allow-Headers': 'authorization, x-client-info, apikey, content-type',
  'Access-Control-Allow-Methods': 'GET, POST, OPTIONS',
};

const DEFAULT_LIMIT = 24;
const MAX_LIMIT = 500;

const OAI_BASE = 'https://directory.doabooks.org/oai/request';
const METADATA_PREFIX = 'xoai';

/**
 * Pages are 100 records, fixed by DSpace — the verb takes no page-size
 * parameter. Roughly half of each page survives the `.pdf` filter
 * (48/100 measured), so one page already covers the rail's 24. The cap
 * bounds worst-case latency for a large `limit`: 6 pages is ~600
 * records, ~290 books, against a function that must answer inside the
 * client's patience rather than fill MAX_LIMIT at any cost.
 */
const MAX_PAGES = 6;

type DiscoverBook = {
  id: string;
  title: string;
  author: string;
  language: string;
  tags: string[];
  coverUrl: string | null;
  /** Surfaced through epubUrl for compatibility with the existing
   * importer call sites — see file header comment for the
   * "PDF-as-EPUB" pragma. */
  epubUrl: string | null;
  formats: Record<string, string>;
  about: string;
  source: 'doab';
  downloadCount: number;
  sourceLabel: string;
};

Deno.serve(async (req) => {
  if (req.method === 'OPTIONS') {
    return new Response('ok', { headers: CORS_HEADERS });
  }
  if (req.method !== 'GET' && req.method !== 'POST') {
    return json({ ok: false, error: 'method_not_allowed' }, 405);
  }

  const url = new URL(req.url);
  const limitParam = Number(url.searchParams.get('limit') ?? DEFAULT_LIMIT);
  const limit = Number.isFinite(limitParam)
    ? Math.min(Math.max(1, limitParam), MAX_LIMIT)
    : DEFAULT_LIMIT;

  // See the header: OAI-PMH cannot search, and pretending to would be
  // worse than saying so.
  const query = url.searchParams.get('q')?.trim();
  if (query) {
    return json(
      {
        ok: false,
        error: 'search_unsupported',
        message:
          'DOAB is harvested over OAI-PMH, which has no search verb. ' +
          'Use the rail without `q`, or search another source.',
      },
      400,
    );
  }

  try {
    const books: DiscoverBook[] = [];
    const seen = new Set<string>();
    let resumptionToken: string | null = null;

    for (let page = 0; page < MAX_PAGES && books.length < limit; page++) {
      // After the first request the verb takes ONLY the resumption
      // token — sending metadataPrefix alongside it is a protocol error
      // (badArgument), not a redundancy.
      const target = new URL(OAI_BASE);
      target.searchParams.set('verb', 'ListRecords');
      if (resumptionToken) {
        target.searchParams.set('resumptionToken', resumptionToken);
      } else {
        target.searchParams.set('metadataPrefix', METADATA_PREFIX);
      }

      const res = await fetch(target.toString(), {
        headers: {
          accept: 'text/xml',
          'user-agent': 'Bookflow/1.0 (https://getbookflow.co)',
        },
        redirect: 'follow',
      });
      if (!res.ok) {
        console.warn(`[discover-doab] upstream returned ${res.status}`);
        // Partial results beat none: if an earlier page already gave us
        // books, serve them rather than failing the whole rail.
        if (books.length > 0) break;
        return json(
          {
            ok: false,
            error: 'upstream_failed',
            message: `DOAB returned ${res.status}`,
          },
          502,
        );
      }

      const xml = await res.text();

      // OAI-PMH reports its own errors inside a 200 response.
      const oaiError = xml.match(/<error\s+code="([^"]+)"\s*>([^<]*)</);
      if (oaiError) {
        console.warn(
          `[discover-doab] OAI error ${oaiError[1]}: ${oaiError[2]}`,
        );
        if (books.length > 0) break;
        return json(
          {
            ok: false,
            error: 'invalid_upstream',
            message: `OAI-PMH error: ${oaiError[1]}`,
          },
          502,
        );
      }

      const recordBlocks = xml.match(/<record>[\s\S]*?<\/record>/g) ?? [];
      for (const record of recordBlocks) {
        const book = normaliseRecord(record);
        if (!book) continue;
        // DOAB occasionally carries the same OAPEN book under two
        // records; the id is derived from the file, so dedupe on it.
        if (seen.has(book.id)) continue;
        seen.add(book.id);
        books.push(book);
        if (books.length >= limit) break;
      }

      const token = xml.match(
        /<resumptionToken[^>]*>([\s\S]*?)<\/resumptionToken>/,
      );
      const next = token ? decodeXmlEntities(token[1]).trim() : '';
      if (!next) break; // end of the list
      resumptionToken = next;
    }

    return json({ ok: true, books }, 200, {
      // Academic OA catalogs move very slowly — DOAB additions land
      // in monthly batches, not daily. 6 h fresh + 24 h SWR keeps
      // upstream calls to a trickle while still rolling forward
      // within a day of any meaningful update. Pairs with the
      // client-side hourly cache bucket in fetchDoabRest, so within
      // any given hour every client + this edge cache converge on
      // the same URL → same response.
      'Cache-Control': 'public, max-age=21600, stale-while-revalidate=86400',
    });
  } catch (err) {
    const message = err instanceof Error ? err.message : String(err);
    console.warn('[discover-doab] fetch threw:', message);
    return json({ ok: false, error: 'network_error', message }, 502);
  }
});

// ─── xoai readers ────────────────────────────────────────────────────────────
//
// xoai nests by element NAME, and the same name recurs at different
// depths, so `<element name="x">([\s\S]*?)</element>` would stop at the
// first inner close tag. These readers count nesting instead.

function escapeRe(s: string): string {
  return s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

/** Inner XML of the first `<element name="NAME">`, or null if absent. */
function elementBlock(xml: string, name: string): string | null {
  const blocks = elementBlocks(xml, name, 1);
  return blocks.length > 0 ? blocks[0] : null;
}

/** Inner XML of every `<element name="NAME">` at any depth, in order. */
function elementBlocks(xml: string, name: string, cap = Infinity): string[] {
  const out: string[] = [];
  const open = new RegExp(`<element\\s+name="${escapeRe(name)}"\\s*(/?)>`, 'g');
  let m: RegExpExecArray | null;
  while (out.length < cap && (m = open.exec(xml))) {
    if (m[1] === '/') {
      out.push(''); // self-closed, no children
      continue;
    }
    const start = m.index + m[0].length;
    const scan = /<element\b[^>]*?(\/?)>|<\/element>/g;
    scan.lastIndex = start;
    let depth = 1;
    let t: RegExpExecArray | null;
    let end = -1;
    while ((t = scan.exec(xml))) {
      if (t[0] === '</element>') {
        if (--depth === 0) {
          end = t.index;
          break;
        }
      } else if (t[1] !== '/') {
        depth++;
      }
    }
    if (end < 0) break; // malformed; stop rather than loop
    out.push(xml.slice(start, end));
    // Resume after this element so nested same-name children are not
    // returned as siblings.
    open.lastIndex = scan.lastIndex;
  }
  return out;
}

/** Every `<field name="NAME">` value directly findable in `block`. */
function fieldValues(block: string, name: string): string[] {
  const re = new RegExp(
    `<field\\s+name="${escapeRe(name)}"\\s*>([\\s\\S]*?)</field>`,
    'g',
  );
  const out: string[] = [];
  let m: RegExpExecArray | null;
  while ((m = re.exec(block))) {
    const v = decodeXmlEntities(m[1]).trim();
    if (v) out.push(v);
  }
  return out;
}

/**
 * Values at a dotted DC path — `dcValues(rec, 'description', 'abstract')`
 * for what the REST adapter called `dc.description.abstract`.
 *
 * The leaf under each path is a language element (`none`, `en`, `*`),
 * so we collect every `value` field beneath it rather than guessing
 * which language bucket a record used.
 */
function dcValues(record: string, ...path: string[]): string[] {
  let block = elementBlock(record, 'dc');
  for (const segment of path) {
    if (block === null) return [];
    block = elementBlock(block, segment);
  }
  return block === null ? [] : fieldValues(block, 'value');
}

function dcFirst(record: string, ...path: string[]): string | undefined {
  const values = dcValues(record, ...path);
  return values.length > 0 ? values[0] : undefined;
}

// ─── Normalisation ───────────────────────────────────────────────────────────

function normaliseRecord(record: string): DiscoverBook | null {
  // Title — xoai has no equivalent of the REST item's `name` label, so
  // dc.title is the only source. A record without one is unusable.
  const title = dcFirst(record, 'title');
  if (!title) return null;

  // Author — DOAB stores per-author rows. Join the first 3 for the
  // card label; the rest aren't worth crowding the UI.
  const authors = dcValues(record, 'contributor', 'author');
  // Authors can be "Last, First" (academic convention). Flip to
  // natural order so cards read normally.
  const author = authors.slice(0, 3).map(flipName).join(', ') || 'Unknown';

  // Language — prefer the ISO-coded field, fall back to free text.
  const langRaw =
    dcFirst(record, 'language', 'iso') ?? dcFirst(record, 'language') ?? '';
  const language = normaliseLanguage(langRaw);

  // Subjects / tags — cap at 6 to match the other sources.
  const tagsRaw = dcValues(record, 'subject');
  const tags: string[] = [];
  for (const t of tagsRaw) {
    const trimmed = t.trim();
    if (!trimmed) continue;
    // Skip classification codes (e.g. "PK1-9601", "thema EDItEUR::...")
    // — they're for librarians, not readers.
    if (/^[A-Z]+\d/.test(trimmed)) continue;
    if (trimmed.includes('::')) continue;
    if (!tags.includes(trimmed)) tags.push(trimmed);
    if (tags.length >= 6) break;
  }

  // Abstract — DOAB uses dc.description.abstract for the readable
  // summary. Some records put it under dc.description instead.
  const aboutRaw =
    dcFirst(record, 'description', 'abstract') ??
    dcFirst(record, 'description') ??
    '';
  const about = truncate(stripHtml(aboutRaw), 280);

  // The download URL, from whichever bitstream carries it.
  //
  // DOAB's bitstream model is unintuitive: for OAPEN-hosted books DOAB
  // itself has no ORIGINAL bitstream. The PDF lives on
  // library.oapen.org and DOAB records that URL as a field on whatever
  // bitstream does exist — usually the THUMBNAIL. Scanning the whole
  // record for the key is what catches both shapes, exactly as the
  // REST adapter did across `item.bitstreams[].metadata`.
  const downloadUrls = fieldValues(record, 'oapenidentifierdownloadUrl');
  const rawPdf = downloadUrls.find((u) => /\.pdf(\?|$)/i.test(u));
  if (!rawPdf) return null;
  const pdfUrl = canonicaliseOapenPdfUrl(rawPdf);

  // Cover — the THUMBNAIL bundle's bitstream. Unlike the REST API's
  // relative `retrieveLink`, xoai's `url` is already absolute.
  let thumbUrl: string | null = null;
  const bundlesBlock = elementBlock(record, 'bundles');
  for (const bundle of bundlesBlock ? elementBlocks(bundlesBlock, 'bundle') : []) {
    // The bundle's own `name` field precedes its `bitstreams` element;
    // the bitstreams carry `name` fields too, so read only the head.
    const bitsIdx = bundle.indexOf('<element name="bitstreams"');
    const head = bitsIdx >= 0 ? bundle.slice(0, bitsIdx) : bundle;
    if ((fieldValues(head, 'name')[0] ?? '') !== 'THUMBNAIL') continue;
    const bits = elementBlock(bundle, 'bitstreams');
    const urls = bits ? fieldValues(bits, 'url') : [];
    if (urls.length > 0) {
      thumbUrl = urls[0];
      break;
    }
  }

  // Derive the Discover id from the OAPEN URL — NOT the DOAB item
  // UUID — so the DiscoverScreen "in library" reverse-map can rebuild
  // the same id from the `books.source_url` column it stores at
  // import time. The DOAB UUID would never appear in the URL; using
  // the OAPEN book id (the second numeric segment of the bitstream
  // path) keeps both sides aligned without a roundtrip lookup.
  // Falls back to the DOAB UUID for any URL we can't pattern-match
  // — those rows simply won't reverse-map and the "Add" button
  // will stay tappable, which is harmless.
  const oapenIdMatch = pdfUrl.match(
    /library\.oapen\.org\/bitstream\/handle\/[\w.]+\/(\d+)\//,
  );
  const others = elementBlock(record, 'others');
  const uuid =
    (others ? fieldValues(others, 'uuid')[0] : undefined) ??
    // Last resort: the OAI identifier, which always exists.
    (record.match(/<identifier>([^<]+)<\/identifier>/)?.[1] ?? 'unknown');
  const id = oapenIdMatch ? `doab:${oapenIdMatch[1]}` : `doab:${uuid}`;

  return {
    id,
    title: title.trim(),
    author,
    language,
    tags,
    coverUrl: proxyCover(thumbUrl),
    epubUrl: pdfUrl,
    formats: { 'application/pdf': pdfUrl },
    about,
    source: 'doab',
    downloadCount: 0,
    sourceLabel: 'DOAB',
  };
}

// ─── Helpers ─────────────────────────────────────────────────────────────────

/**
 * OAPEN's bitstream URLs come in two flavours:
 *   short:  /bitstream/{handlePrefix}/{bookId}/{seq}/{filename}.pdf
 *   handle: /bitstream/handle/{handlePrefix}/{bookId}/{filename}.pdf?sequence={seq}
 *
 * The short form 301-redirects to the handle form — BUT OAPEN's
 * DSpace tacks `;jsessionid=…` (a J2EE matrix parameter) onto the
 * redirect Location. Deno's fetch throws when it tries to parse and
 * follow that URL, so the edge function never gets the file. (curl
 * follows it fine; tested both with and without jsessionid and the
 * handle form returns the same 200 + PDF either way.)
 *
 * We rewrite the short form to the canonical handle form server-side
 * — no redirect needed, no jsessionid involved. If the URL doesn't
 * match the short pattern (other OAPEN paths, future variations) we
 * return it unchanged and let the importer try; worst case the
 * record is dropped and the user moves on.
 */
function canonicaliseOapenPdfUrl(url: string): string {
  // Match host first so we don't accidentally rewrite non-OAPEN URLs
  // that happen to share path structure.
  if (!/^https?:\/\/library\.oapen\.org\//i.test(url)) return url;
  const m = url.match(
    /^(https?:\/\/library\.oapen\.org)\/bitstream\/([\w.]+)\/(\d+)\/(\d+)\/([^?#]+\.pdf)$/i,
  );
  if (!m) return url;
  const [, origin, handlePrefix, bookId, sequence, filename] = m;
  return `${origin}/bitstream/handle/${handlePrefix}/${bookId}/${filename}?sequence=${sequence}`;
}

/**
 * "Last, First" → "First Last". Tolerant of names with no comma
 * (returned unchanged) and multi-comma names (only the first comma
 * is treated as the separator).
 */
function flipName(s: string): string {
  const trimmed = s.trim();
  const i = trimmed.indexOf(',');
  if (i <= 0) return trimmed;
  const last = trimmed.slice(0, i).trim();
  const first = trimmed.slice(i + 1).trim();
  if (!last || !first) return trimmed;
  return `${first} ${last}`;
}

const THREE_TO_TWO: Record<string, string> = {
  eng: 'en',
  fre: 'fr',
  fra: 'fr',
  ger: 'de',
  deu: 'de',
  spa: 'es',
  ita: 'it',
  por: 'pt',
  rus: 'ru',
  chi: 'zh',
  zho: 'zh',
  jpn: 'ja',
  kor: 'ko',
  ara: 'ar',
  lat: 'la',
  grc: 'el',
  nld: 'nl',
  pol: 'pl',
};

/** Reduce whatever DOAB gives us (ISO 639-3, region-tagged, free-text)
 * to a leading ISO 639-1 code for UI consistency. Best-effort —
 * returns empty for unmappable inputs. */
function normaliseLanguage(raw: string): string {
  const trimmed = raw.trim().toLowerCase();
  if (!trimmed) return '';
  // Region-tagged (en-US, fr-FR): take leading code.
  const prefix = trimmed.split(/[-_]/)[0] ?? '';
  if (prefix.length === 2) return prefix;
  if (prefix.length === 3) return THREE_TO_TWO[prefix] ?? '';
  return '';
}

function stripHtml(s: string): string {
  return s.replace(/<[^>]+>/g, '');
}

function truncate(s: string, max: number): string {
  const trimmed = s.trim();
  if (trimmed.length <= max) return trimmed;
  return `${trimmed.slice(0, max - 1)}…`;
}

/** xoai escapes markup inside field values; abstracts in particular
 * arrive with `&amp;` and `&#39;`. Mirrors discover-opds. */
function decodeXmlEntities(s: string): string {
  return s
    .replace(/&lt;/g, '<')
    .replace(/&gt;/g, '>')
    .replace(/&quot;/g, '"')
    .replace(/&#39;/g, "'")
    .replace(/&apos;/g, "'")
    // Ampersand last: decoding it first would turn `&amp;lt;` into `<`.
    .replace(/&amp;/g, '&');
}

/** Run cover URLs through images.weserv.nl — same pipeline as the
 * Gutenberg / Standard Ebooks / OPDS adapters. Keeps payload small,
 * caches at the edge, normalises HTTPS. */
function proxyCover(src: string | null): string | null {
  if (!src) return null;
  const stripped = src.replace(/^https?:\/\//, '');
  return `https://images.weserv.nl/?url=${encodeURIComponent(stripped)}&w=240&output=webp&q=80&we`;
}

function json(
  payload: unknown,
  status: number,
  extraHeaders: Record<string, string> = {},
) {
  return new Response(JSON.stringify(payload), {
    status,
    headers: {
      ...CORS_HEADERS,
      'Content-Type': 'application/json',
      ...extraHeaders,
    },
  });
}
